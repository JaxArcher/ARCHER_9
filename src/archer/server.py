# --- Browser client event bridge ---
# Forwards the internal event bus (archer.core.event_bus — the same one
# the PyQt6 ConversationPanel subscribes to, see gui/conversation.py) to
# every connected browser client over WebSocket. Message schema is
# documented in web/CONTRACT.md — that file is the interface contract for
# building/restyling the browser UI without touching this Python.
#
# The event bus calls subscriber callbacks SYNCHRONOUSLY on whatever
# thread published the event (the voice pipeline runs on its own thread,
# not the asyncio loop) — so callbacks can't just `await ws.send_text()`
# directly. Instead they hand the message to the asyncio loop thread-
# safely via call_soon_threadsafe, and a loop-side function does the
# actual broadcast.
_ws_clients: set[WebSocket] = set()
_ws_loop: asyncio.AbstractEventLoop | None = None


async def _ws_send_safe(ws: WebSocket, text: str) -> None:
    try:
        await ws.send_text(text)
    except Exception as e:
        logger.warning(f"[ServerWS] _ws_send_safe failed: {e}")
        _ws_clients.discard(ws)
        _technical_subscribers.discard(ws)


def _broadcast_ws(msg: dict) -> None:
    """Broadcast a JSON message to all connected WebSocket clients.
    Thread-safe: can be called from within the asyncio loop OR from any worker thread."""
    if not _ws_clients:
        return

    # If called from a non-loop thread or outside an active event loop,
    # schedule onto _ws_loop via call_soon_threadsafe.
    if _ws_loop is not None and _ws_loop.is_running():
        try:
            current_loop = asyncio.get_running_loop()
        except RuntimeError:
            current_loop = None

        if current_loop is not _ws_loop:
            try:
                _ws_loop.call_soon_threadsafe(_broadcast_ws, msg)
            except RuntimeError:
                pass
            return

    # Running on the event loop: create send tasks safely
    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        return

    text = json.dumps(msg, default=str)
    for ws in list(_ws_clients):
        loop.create_task(_ws_send_safe(ws, text))


# --- Dedicated binary Android frame streaming (Phase 7b, review 2026-10-21) ---
_android_ws_clients: set[WebSocket] = set()
_android_client_sending: dict[WebSocket, bool] = {}


def _dispatch_android_frame_bytes(jpeg_bytes: bytes, width: int, height: int) -> None:
    """Send binary JPEG frame only over /ws/android with per-client backpressure (drop old frames)."""
    if not _android_ws_clients or _ws_loop is None or not _ws_loop.is_running():
        return

    async def _send_to_client(ws: WebSocket, payload: bytes):
        try:
            await ws.send_bytes(payload)
        except Exception as e:
            logger.debug(f"[AndroidWS] send_bytes error: {e}")
            _android_ws_clients.discard(ws)
            _android_client_sending.pop(ws, None)
        finally:
            _android_client_sending[ws] = False

    def _schedule():
        for ws in list(_android_ws_clients):
            # Backpressure: If client is still sending previous frame, drop this one!
            if _android_client_sending.get(ws, False):
                continue
            _android_client_sending[ws] = True
            asyncio.create_task(_send_to_client(ws, jpeg_bytes))

    try:
        _ws_loop.call_soon_threadsafe(_schedule)
    except RuntimeError:
        pass


def _on_bus_event(msg_type: str, **data) -> None:
    """Build a browser-facing message and hand it to the asyncio loop thread-safely."""
    if _ws_loop is None:
        return  # no browser client has connected yet
    msg = {"type": msg_type, **data}
    try:
        _ws_loop.call_soon_threadsafe(_broadcast_ws, msg)
    except RuntimeError:
        pass  # loop already closed/shutting down


