    entry = {
        "id": str(uuid.uuid4()),
        "timestamp": ts,
        "part": part,
        "level": level,
        "text": text,
        "details": details_str,
    }
    _activity_feed_history.append(entry)

    line = f"{ts} | {text}\n"
    _status_line_history.append(line)

    _broadcast_ws({
        "type": "logs_feed_entry",
        "entry": entry,
    })
    _broadcast_ws({
        "type": "log_line",
        "text": line,
    })


