def _status_board_monitor_loop() -> None:
    """Periodic check for Observer heartbeat and background jobs."""
    global _last_observer_audio_stalled
    from archer.memory.sqlite_store import get_sqlite_store
    import time

    while True:
        try:
            store = get_sqlite_store()
            curr = time.time()
            try:
                row = store._listening_row()
                heartbeat = float(row.get("listener_heartbeat", 0.0) or 0.0)
                is_stale = (curr - heartbeat) > 15.0
            except Exception:
                is_stale = True

            if is_stale:
                _update_status_board(
                    "observer", "Stopped",
                    "Stopped -- no heartbeat from ArcherObserver service.",
                    dot="red", is_error=True
                )
            else:
                status = store.get_listening_status(stale_after=15.0)
                room_state = status.get("state", "listening")
                people_cnt = 0
                try:
                    with store._get_connection() as conn:
                        c = conn.execute("SELECT COUNT(DISTINCT person_id) FROM person_stays WHERE ended_at IS NULL").fetchone()
                        if c:
                            people_cnt = c[0]
                except Exception:
                    pass
                people_str = "1 person in view" if people_cnt == 1 else f"{people_cnt} people in view"
                item_on = os.environ.get("ARCHER_ITEMS_WATCH", "false").lower() == "true"
                item_str = "Item watcher on" if item_on else "Item watcher off"

                # Check audio stall status (Claude 2026-10-21, 16:30 review)
                audio_stalled_sec = float(row.get("audio_stalled_seconds", 0.0) or 0.0)
                last_audio_at = float(row.get("audio_last_received_at", 0.0) or 0.0)
                is_audio_stalled = False
                stall_elapsed = 0

                if audio_stalled_sec > 0.0:
                    is_audio_stalled = True
                    stall_elapsed = int(audio_stalled_sec)
                elif room_state == "listening" and last_audio_at > 0.0 and (curr - last_audio_at) >= 10.0:
                    is_audio_stalled = True
                    stall_elapsed = int(curr - last_audio_at)

                if is_audio_stalled:
                    dot = "amber" if stall_elapsed < 30 else "red"
                    _update_status_board(
                        "observer", "Audio Stalled",
                        f"Running | room listening: no audio for {stall_elapsed} s | {people_str} | {item_str}",
                        dot=dot, is_error=(stall_elapsed >= 30)
                    )
                    if not _last_observer_audio_stalled:
                        _last_observer_audio_stalled = True
                        _log_activity("Observer", f"⚠️ Room audio stalled: no audio received from camera for {stall_elapsed} s.", level="warning")
                else:
                    if _last_observer_audio_stalled:
                        _last_observer_audio_stalled = False
                        _log_activity("Observer", "🎧 Room audio reconnected and streaming.")
                    _update_status_board(
                        "observer", "Running",
                        f"Running | Room listening {room_state} | {people_str} | {item_str}",
                        dot="green", is_error=False
                    )

            redis_ok = False
            chroma_ok = False
            try:
                from archer.memory.redis_buffer import get_redis_buffer
                rb = get_redis_buffer()
                if rb._client:
                    rb._client.ping()
                    redis_ok = True
            except Exception:
                redis_ok = False

            try:
                from archer.memory.chromadb_store import get_chromadb_store
                cb = get_chromadb_store()
                if cb.is_available:
                    chroma_ok = True
            except Exception:
                chroma_ok = False

            jobs_desc = f"Redis: {'OK' if redis_ok else 'Offline'} | ChromaDB: {'OK' if chroma_ok else 'Offline'} | Ollama: OK | Maint: 03:00 AM"
            jobs_dot = "green" if (redis_ok and chroma_ok) else "amber"
            _update_status_board("jobs", "Healthy" if (redis_ok and chroma_ok) else "Degraded", jobs_desc, dot=jobs_dot)

            try:
                from archer.voice import get_audio_manager
                am = get_audio_manager()
                if not am.is_loopback_available:
                    _update_status_board(
                        "voice",
                        "Warning",
                        "TV check off: can't hear the PC's sound.",
                        dot="red",
                        is_error=True,
                    )
            except Exception:
                pass

            if _ws_clients:
                _broadcast_ws({"type": "logs_status_board", "board": _status_board_state})

        except Exception as e:
            logger.debug(f"[StatusBoardMonitor] Error in loop: {e}")

        time.sleep(3.0)


