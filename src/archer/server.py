@app.websocket("/ws/android")
async def ws_android(websocket: WebSocket):
    """
    Dedicated binary frame streaming WebSocket for the ANDROID tab (Phase 7b review).
    Carries raw JPEG bytes (zero base64/JSON overhead) with per-client backpressure.
    Streaming runs only while at least one /ws/android client is connected and active.
    """
    global _ws_loop
    await websocket.accept()
    if _ws_loop is None:
        _ws_loop = asyncio.get_running_loop()
    _android_ws_clients.add(websocket)
    _android_client_sending[websocket] = False
    logger.info(f"Android stream client connected ({len(_android_ws_clients)} total)")

    from archer.android_manager import get_android_manager
    mgr = get_android_manager()
    mgr.set_streaming_active(True)

    # Immediately deliver latest frame if available
    if mgr.last_frame_bytes:
        try:
            await websocket.send_bytes(mgr.last_frame_bytes)
        except Exception:
            pass

    try:
        while True:
            raw = await websocket.receive_text()
            try:
                msg = json.loads(raw)
                mtype = msg.get("type")
                if mtype == "resize":
                    mgr.set_stream_resolution(msg.get("width", 0), msg.get("height", 0))
                elif mtype == "visibility":
                    vis = bool(msg.get("visible", True))
                    mgr.set_streaming_active(vis and len(_android_ws_clients) > 0)
                elif mtype == "android_touch":
                    action = msg.get("action", "down")
                    x = float(msg.get("x", 0.0))
                    y = float(msg.get("y", 0.0))
                    await mgr.handle_touch(action, x, y)
                elif mtype == "android_button":
                    btn = msg.get("button", "")
                    rot = msg.get("rotation")
                    await mgr.handle_button(btn, rotation=rot)
                elif mtype == "android_key":
                    action = msg.get("action", "down")
                    key = msg.get("key", "")
                    code = msg.get("code", "")
                    text = msg.get("text")
                    await mgr.handle_key(action, key, code, text=text)
            except Exception as e:
                logger.debug(f"[AndroidWS] Command handling error: {e}")
    except WebSocketDisconnect:
        pass
    finally:
        _android_ws_clients.discard(websocket)
        _android_client_sending.pop(websocket, None)
        if not _android_ws_clients:
            mgr.set_streaming_active(False)
        logger.info(f"Android stream client disconnected ({len(_android_ws_clients)} total)")


def _person_snapshot_data_uri(snapshot_path: Optional[str]) -> Optional[str]:
    """Read a face snapshot JPEG off disk and inline it as a data: URI for
    the browser -- these files live under data/snapshots/ (see
    person_id.py) and were never served over HTTP before, so the simplest
    fix is embedding the bytes directly in the WS payload rather than
    adding a new static route. Best-effort: a missing/unreadable file just
    means no thumbnail, not a broken pane."""
    if not snapshot_path:
        return None
    try:
        raw = Path(snapshot_path).read_bytes()
        import base64
        return "data:image/jpeg;base64," + base64.b64encode(raw).decode("ascii")
    except Exception as e:
        logger.debug(f"Could not read person snapshot '{snapshot_path}': {e}")
        return None


