def _update_status_board(part: str, state: str, desc: str, dot: Optional[str] = None, is_error: bool = False, broadcast: bool = True) -> None:
    global _last_board_broadcast
    card = _status_board_state.get(part)
    if not card:
        return
    changed = (card.get("state") != state or card.get("desc") != desc or (dot is not None and card.get("dot") != dot))
    if card.get("state") != state:
        card["since"] = _time.time()
    card["state"] = state
    card["desc"] = desc
    if dot is not None:
        card["dot"] = dot
    card["is_error"] = is_error

    if broadcast and (changed or (_time.time() - _last_board_broadcast > 4.0)):
        _last_board_broadcast = _time.time()
        _broadcast_ws({"type": "logs_status_board", "board": _status_board_state})


