/**
 * ARCHER browser client — ARTIFACTS tab renderer (Phase 5, Spec Section 8).
 * Displays documents and assets generated in data/artifacts/.
 * Provides native Open (Word, PowerPoint, Excel, PDF), Show in Folder, and direct previews.
 */
(() => {
  const container = document.getElementById("archer-artifacts-view");
  if (!container) return;

  let allArtifacts = [];
  let currentFilter = "all";
  let selectedFile = null;

  function escapeHtml(s) {
    return String(s ?? "").replace(/[&<>"']/g, (c) => ({
      "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
    }[c]));
  }

  function formatBytes(bytes) {
    if (!bytes || bytes === 0) return "0 B";
    const k = 1024;
    const sizes = ["B", "KB", "MB", "GB"];
    const i = Math.floor(Math.log(bytes) / Math.log(k));
    return parseFloat((bytes / Math.pow(k, i)).toFixed(1)) + " " + sizes[i];
  }

  function getBadgeClass(ext) {
    ext = (ext || "").toLowerCase();
    if (ext === "docx" || ext === "doc") return "badge-docx";
    if (ext === "pptx" || ext === "ppt") return "badge-pptx";
    if (ext === "xlsx" || ext === "xls" || ext === "csv") return "badge-xlsx";
    if (ext === "pdf") return "badge-pdf";
    if (["png", "jpg", "jpeg", "webp", "gif", "svg"].includes(ext)) return "badge-image";
    if (ext === "diff" || ext === "patch") return "badge-diff";
    return "badge-other";
  }

  function isPreviewableDirectly(ext) {
    ext = (ext || "").toLowerCase();
    return ["png", "jpg", "jpeg", "webp", "gif", "svg", "md", "txt", "json", "csv", "diff", "patch", "py"].includes(ext);
  }

  function isImage(ext) {
    return ["png", "jpg", "jpeg", "webp", "gif", "svg"].includes((ext || "").toLowerCase());
  }

  function isText(ext) {
    return ["md", "txt", "json", "csv", "log", "diff", "patch", "py"].includes((ext || "").toLowerCase());
  }

  function renderLayout() {
    container.innerHTML = `
      <div class="artifacts-header">
        <div>
          <h3>Artifacts &amp; Documents</h3>
          <p class="archer-memory-hint">Files generated by ARCHER in <code>data/artifacts/</code>. Open in native Office / PDF apps or preview directly.</p>
        </div>
        <div class="artifacts-controls">
          <div class="artifacts-filters">
            <button type="button" class="artifact-filter-btn active" data-filter="all">ALL</button>
            <button type="button" class="artifact-filter-btn" data-filter="docx">WORD</button>
            <button type="button" class="artifact-filter-btn" data-filter="pptx">POWERPOINT</button>
            <button type="button" class="artifact-filter-btn" data-filter="xlsx">EXCEL</button>
            <button type="button" class="artifact-filter-btn" data-filter="pdf">PDF</button>
            <button type="button" class="artifact-filter-btn" data-filter="media">PREVIEWABLE</button>
          </div>
          <button id="artifacts-refresh-btn" type="button" class="artifact-btn" title="Refresh files list">&#x21BB; Refresh</button>
        </div>
      </div>
      <div id="artifacts-feedback" class="artifacts-feedback" style="display:none;"></div>
      <div class="artifacts-body">
        <div class="artifacts-list-wrap">
          <table class="artifacts-table">
            <thead>
              <tr>
                <th>Artifact</th>
                <th>Type</th>
                <th>Size</th>
                <th>Modified</th>
                <th>Actions</th>
              </tr>
            </thead>
            <tbody id="artifacts-table-body">
              <tr><td colspan="5" class="archer-memory-empty">Loading artifacts...</td></tr>
            </tbody>
          </table>
        </div>
        <div id="artifacts-preview-pane" class="artifacts-preview-pane">
          <div class="artifacts-preview-placeholder">
            <span class="preview-icon">&#x1F4C4;</span>
            <p>Select an artifact to view details or launch natively.</p>
          </div>
        </div>
      </div>
    `;

    // Bind controls
    const refreshBtn = container.querySelector("#artifacts-refresh-btn");
    if (refreshBtn) {
      refreshBtn.addEventListener("click", () => fetchArtifacts());
    }

    const filterBtns = container.querySelectorAll(".artifact-filter-btn");
    filterBtns.forEach((btn) => {
      btn.addEventListener("click", () => {
        filterBtns.forEach((b) => b.classList.remove("active"));
        btn.classList.add("active");
        currentFilter = btn.dataset.filter;
        renderTableRows();
      });
    });
  }

  function showFeedback(text, isError = false) {
    const fb = container.querySelector("#artifacts-feedback");
    if (!fb) return;
    fb.textContent = text;
    fb.className = `artifacts-feedback ${isError ? "is-error" : "is-success"}`;
    fb.style.display = "block";
    setTimeout(() => {
      fb.style.display = "none";
    }, 4000);
  }

  function renderTableRows() {
    const tbody = container.querySelector("#artifacts-table-body");
    if (!tbody) return;

    let filtered = allArtifacts;
    if (currentFilter === "docx") {
      filtered = allArtifacts.filter((a) => a.extension === "docx" || a.extension === "doc");
    } else if (currentFilter === "pptx") {
      filtered = allArtifacts.filter((a) => a.extension === "pptx" || a.extension === "ppt");
    } else if (currentFilter === "xlsx") {
      filtered = allArtifacts.filter((a) => a.extension === "xlsx" || a.extension === "xls" || a.extension === "csv");
    } else if (currentFilter === "pdf") {
      filtered = allArtifacts.filter((a) => a.extension === "pdf");
    } else if (currentFilter === "media") {
      filtered = allArtifacts.filter((a) => isPreviewableDirectly(a.extension));
    }

    if (!filtered || !filtered.length) {
      tbody.innerHTML = `<tr><td colspan="5" class="archer-memory-empty">No artifacts found in data/artifacts/.</td></tr>`;
      return;
    }

    tbody.innerHTML = filtered.map((item) => {
      const isSelected = selectedFile && selectedFile.name === item.name;
      const ext = item.extension ? item.extension.toUpperCase() : "FILE";
      return `
        <tr class="artifact-row ${isSelected ? "is-selected" : ""}" data-filename="${escapeHtml(item.name)}">
          <td class="artifact-name-cell">
            <span class="artifact-item-icon">${getFileIcon(item.extension)}</span>
            <span class="artifact-item-name" title="${escapeHtml(item.name)}">${escapeHtml(item.name)}</span>
          </td>
          <td><span class="artifact-badge ${getBadgeClass(item.extension)}">${escapeHtml(ext)}</span></td>
          <td class="artifact-size-cell">${escapeHtml(formatBytes(item.size_bytes))}</td>
          <td class="artifact-time-cell">${escapeHtml(item.modified_at || "")}</td>
          <td class="artifact-actions-cell">
            <button type="button" class="artifact-action-btn btn-open" data-path="${escapeHtml(item.path || item.name)}" title="Open in native program">Open</button>
            <button type="button" class="artifact-action-btn btn-folder" data-path="${escapeHtml(item.path || item.name)}" title="Show in File Explorer">Folder</button>
          </td>
        </tr>
      `;
    }).join("");

    // Row selection and button actions
    tbody.querySelectorAll(".artifact-row").forEach((row) => {
      row.addEventListener("click", (e) => {
        if (e.target.closest(".artifact-action-btn")) return;
        const filename = row.dataset.filename;
        const file = allArtifacts.find((f) => f.name === filename);
        if (file) selectArtifact(file);
      });
    });

    tbody.querySelectorAll(".btn-open").forEach((btn) => {
      btn.addEventListener("click", (e) => {
        e.stopPropagation();
        openArtifactNatively(btn.dataset.path);
      });
    });

    tbody.querySelectorAll(".btn-folder").forEach((btn) => {
      btn.addEventListener("click", (e) => {
        e.stopPropagation();
        showArtifactInFolder(btn.dataset.path);
      });
    });
  }

  function getFileIcon(ext) {
    ext = (ext || "").toLowerCase();
    if (ext === "docx" || ext === "doc") return "&#x1F4D6;";
    if (ext === "pptx" || ext === "ppt") return "&#x1F4CA;";
    if (ext === "xlsx" || ext === "xls" || ext === "csv") return "&#x1F522;";
    if (ext === "pdf") return "&#x1F4D5;";
    if (isImage(ext)) return "&#x1F5BC;";
    return "&#x1F4C4;";
  }

  async function selectArtifact(file) {
    selectedFile = file;
    renderTableRows();

    const previewPane = container.querySelector("#artifacts-preview-pane");
    if (!previewPane) return;

    const ext = (file.extension || "").toLowerCase();
    const encodedName = encodeURIComponent(file.name);
    const fileUrl = `/artifacts/${encodedName}`;

    let previewContent = "";

    if (isImage(ext)) {
      previewContent = `
        <div class="artifact-image-preview-wrap">
          <img src="${fileUrl}" alt="${escapeHtml(file.name)}" class="artifact-image-preview" />
        </div>
      `;
    } else if (isText(ext)) {
      previewContent = `
        <div class="artifact-text-loading">Loading content...</div>
        <pre class="artifact-text-preview" id="artifact-text-body"></pre>
      `;
      // Fetch text asynchronously
      fetch(fileUrl)
        .then((r) => r.text())
        .then((txt) => {
          const body = previewPane.querySelector("#artifact-text-body");
          const ldg = previewPane.querySelector(".artifact-text-loading");
          if (ldg) ldg.style.display = "none";
          if (body) body.textContent = txt;
        })
        .catch((err) => {
          const ldg = previewPane.querySelector(".artifact-text-loading");
          if (ldg) ldg.textContent = "Could not load preview.";
        });
    } else {
      // Office / PDF Document Card (Spec Section 8: Open buttons only, no internal conversion)
      let docTypeLabel = "Document";
      if (ext === "docx") docTypeLabel = "Microsoft Word Document";
      else if (ext === "pptx") docTypeLabel = "PowerPoint Presentation (16:9)";
      else if (ext === "xlsx") docTypeLabel = "Excel Spreadsheet";
      else if (ext === "pdf") docTypeLabel = "PDF Document";

      previewContent = `
        <div class="artifact-native-card">
          <div class="native-card-icon">${getFileIcon(ext)}</div>
          <div class="native-card-title">${escapeHtml(docTypeLabel)}</div>
          <p class="native-card-desc">Click below to launch this file in your native application.</p>
          <div class="native-card-actions">
            <button type="button" class="artifact-launch-btn btn-primary-launch" id="preview-btn-open">
              &#x25B6; Open in ${ext.toUpperCase()}
            </button>
            <button type="button" class="artifact-launch-btn btn-secondary-launch" id="preview-btn-folder">
              &#x1F4C2; Show in Folder
            </button>
          </div>
        </div>
      `;
    }

    previewPane.innerHTML = `
      <div class="artifact-detail-header">
        <div class="artifact-detail-title-group">
          <span class="artifact-detail-icon">${getFileIcon(ext)}</span>
          <div>
            <div class="artifact-detail-name" title="${escapeHtml(file.name)}">${escapeHtml(file.name)}</div>
            <div class="artifact-detail-meta">${escapeHtml(formatBytes(file.size_bytes))} &bull; Modified ${escapeHtml(file.modified_at || "")}</div>
          </div>
        </div>
        <div class="artifact-detail-quick-actions">
          <button type="button" class="artifact-btn" id="preview-top-open">Open</button>
          <button type="button" class="artifact-btn" id="preview-top-folder">Folder</button>
        </div>
      </div>
      <div class="artifact-detail-path">Path: <code>${escapeHtml(file.path || file.name)}</code></div>
      <div class="artifact-detail-body">
        ${previewContent}
      </div>
    `;

    // Hook buttons
    const bOpen = previewPane.querySelector("#preview-btn-open");
    if (bOpen) bOpen.addEventListener("click", () => openArtifactNatively(file.path || file.name));

    const bFolder = previewPane.querySelector("#preview-btn-folder");
    if (bFolder) bFolder.addEventListener("click", () => showArtifactInFolder(file.path || file.name));

    const bTopOpen = previewPane.querySelector("#preview-top-open");
    if (bTopOpen) bTopOpen.addEventListener("click", () => openArtifactNatively(file.path || file.name));

    const bTopFolder = previewPane.querySelector("#preview-top-folder");
    if (bTopFolder) bTopFolder.addEventListener("click", () => showArtifactInFolder(file.path || file.name));
  }

  async function openArtifactNatively(path) {
    if (window.ArcherClient && window.ArcherClient.sendOpenArtifact) {
      window.ArcherClient.sendOpenArtifact(path);
      showFeedback(`Opening ${path.split(/[\\/]/).pop()}...`);
      return;
    }

    try {
      const res = await fetch("/api/artifacts/open", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ filepath: path }),
      });
      const data = await res.json();
      if (data.status === "success") {
        showFeedback(data.message || "Opened document natively.");
      } else {
        showFeedback(data.error || "Could not open document.", true);
      }
    } catch (e) {
      showFeedback(`Error opening document: ${e.message}`, true);
    }
  }

  async function showArtifactInFolder(path) {
    if (window.ArcherClient && window.ArcherClient.sendShowArtifactInFolder) {
      window.ArcherClient.sendShowArtifactInFolder(path);
      showFeedback(`Opening in Explorer: ${path.split(/[\\/]/).pop()}...`);
      return;
    }

    try {
      const res = await fetch("/api/artifacts/show_in_folder", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ filepath: path }),
      });
      const data = await res.json();
      if (data.status === "success") {
        showFeedback(data.message || "Showed in File Explorer.");
      } else {
        showFeedback(data.error || "Could not show in folder.", true);
      }
    } catch (e) {
      showFeedback(`Error: ${e.message}`, true);
    }
  }

  async function fetchArtifacts() {
    try {
      if (window.ArcherClient && window.ArcherClient.sendGetArtifacts) {
        window.ArcherClient.sendGetArtifacts();
      }

      const res = await fetch("/api/artifacts");
      if (res.ok) {
        const data = await res.json();
        allArtifacts = data.files || [];
        renderTableRows();

        if (selectedFile) {
          const fresh = allArtifacts.find((f) => f.name === selectedFile.name);
          if (fresh) selectArtifact(fresh);
        } else if (allArtifacts.length > 0) {
          selectArtifact(allArtifacts[0]);
        }
      }
    } catch (e) {
      console.warn("[artifacts] Failed to load artifacts:", e);
    }
  }

  renderLayout();
  fetchArtifacts();

  // Listen to WebSocket events
  if (window.ArcherClient) {
    window.ArcherClient.on("artifactsList", (files) => {
      allArtifacts = files || [];
      renderTableRows();
      if (selectedFile) {
        const fresh = allArtifacts.find((f) => f.name === selectedFile.name);
        if (fresh) selectArtifact(fresh);
      } else if (allArtifacts.length > 0) {
        selectArtifact(allArtifacts[0]);
      }
    });

    window.ArcherClient.on("artifactDisplay", (evt) => {
      fetchArtifacts().then(() => {
        if (evt.filename) {
          const match = allArtifacts.find((f) => f.name === evt.filename);
          if (match) selectArtifact(match);
        }
      });
      showFeedback(`New artifact: ${evt.filename || "file created"}`);
    });

    window.ArcherClient.on("artifactPush", () => {
      fetchArtifacts();
    });

    window.ArcherClient.on("artifactActionResult", (msg) => {
      if (msg.result && msg.result.status === "success") {
        showFeedback(msg.result.message || "Action successful.");
      } else if (msg.result && msg.result.error) {
        showFeedback(msg.result.error, true);
      }
    });
  }

  // Refresh when switching to ARTIFACTS tab
  window.addEventListener("archer-tab-changed", (evt) => {
    if (evt.detail && evt.detail.activeTab === "artifacts") {
      fetchArtifacts();
    }
  });
})();
